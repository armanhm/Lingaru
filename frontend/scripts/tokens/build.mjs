// Generates src/design/tokens.css and design/paper.tokens.json from src/design/tokens.json.
// Usage: node scripts/tokens/build.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../../', import.meta.url);
const SOURCE = new URL('src/design/tokens.json', root);
const CSS_OUT = new URL('src/design/tokens.css', root);
const ARTIFACT_OUT = new URL('design/paper.tokens.json', root);

const rem = (px) => `${+(px / 16).toFixed(4)}rem`;

export function buildCss(tokens) {
  const out = [
    '/* Generated by scripts/tokens/build.mjs from tokens.json. Do not edit by hand. */',
    '@theme {',
  ];
  for (const [ramp, steps] of Object.entries(tokens.ramps)) {
    for (const [step, hex] of Object.entries(steps)) {
      out.push(`  --color-${ramp}-${step}: ${hex};`);
    }
  }
  for (const [alias, ramp] of Object.entries(tokens.aliases)) {
    for (const step of Object.keys(tokens.ramps[ramp])) {
      out.push(`  --color-${alias}-${step}: var(--color-${ramp}-${step});`);
    }
  }
  for (const [name, value] of Object.entries(tokens.fonts)) {
    out.push(`  --font-${name}: ${value};`);
  }
  for (const [name, t] of Object.entries(tokens.type)) {
    if (t.family) continue; // emitted as @utility below
    out.push(`  --text-${name}: ${rem(t.size)};`);
    out.push(`  --text-${name}--line-height: ${t.lineHeight};`);
    if (t.letterSpacing) out.push(`  --text-${name}--letter-spacing: ${t.letterSpacing};`);
    if (t.weight) out.push(`  --text-${name}--font-weight: ${t.weight};`);
  }
  out.push('}', '');
  for (const [selector, mode] of [[':root', 'light'], ['.dark', 'dark']]) {
    out.push(`${selector} {`);
    for (const [name, v] of Object.entries(tokens.semantic)) {
      out.push(`  --pp-${name}: ${v[mode]};`);
    }
    out.push('}', '');
  }
  for (const [name, t] of Object.entries(tokens.type)) {
    if (!t.family) continue;
    out.push(
      `@utility text-${name} {`,
      `  font-family: var(--font-${t.family});`,
      `  font-size: ${rem(t.size)};`,
      `  line-height: ${t.lineHeight};`,
      `  font-weight: ${t.weight} !important;`,
      '  letter-spacing: normal;',
      '}',
      '',
    );
  }
  out.push('@theme inline {');
  for (const name of Object.keys(tokens.semantic)) {
    out.push(`  --color-${name}: var(--pp-${name});`);
  }
  out.push('}', '');
  return out.join('\n');
}

const style = (name, t) => ({
  name,
  fontSize: `${t.size}px`,
  lineHeight: t.lineHeight,
  fontWeight: t.weight ?? 400,
  ...(t.letterSpacing ? { letterSpacing: t.letterSpacing } : {}),
});

export function buildArtifactTokens(tokens) {
  const colour = Object.entries(tokens.semantic).map(([name, v]) => ({
    name,
    value: { light: v.light, dark: v.dark },
    usage: v.usage,
  }));
  for (const [ramp, steps] of Object.entries(tokens.ramps)) {
    for (const [step, hex] of Object.entries(steps)) {
      colour.push({ name: `${ramp}-${step}`, value: hex, usage: `${ramp} ramp.` });
    }
  }
  const pick = (names) => names.map((n) => style(n, tokens.type[n]));
  return {
    name: 'Lingaru Paper',
    version: 1,
    color: {
      themes: [
        { id: 'light', name: 'Light' },
        { id: 'dark', name: 'Dark' },
      ],
      tokens: colour,
    },
    type: {
      fonts: [],
      families: {
        serif: '"Instrument Serif", ui-serif, Georgia, serif',
        sans: '"Inter", ui-sans-serif, system-ui, sans-serif',
        mono: '"JetBrains Mono", ui-monospace, monospace',
      },
      groups: [
        { name: 'Headings', family: 'serif', styles: pick(['display', 'h1', 'h2', 'h3']) },
        {
          name: 'Text',
          family: 'sans',
          styles: pick(['h4', 'body-lg', 'body', 'small', 'caption', 'eyebrow']),
        },
      ],
    },
    spacing: {
      tokens: tokens.space.map((s, i) => ({
        name: `space-${i + 1}`,
        value: `${s.value}px`,
        usage: s.usage,
      })),
    },
    radius: {
      tokens: Object.entries(tokens.radius).map(([k, r]) => ({
        name: `radius-${k}`,
        value: r.value,
        usage: r.usage,
      })),
    },
  };
}

function main() {
  const tokens = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const files = [
    [CSS_OUT, buildCss(tokens)],
    [ARTIFACT_OUT, JSON.stringify(buildArtifactTokens(tokens), null, 2) + '\n'],
  ];
  if (process.argv.includes('--check')) {
    const stale = files.filter(
      ([url, text]) => !existsSync(url) || readFileSync(url, 'utf8') !== text,
    );
    if (stale.length) {
      for (const [url] of stale) console.error(`stale: ${fileURLToPath(url)}`);
      console.error('Run `npm run tokens` and commit the result.');
      process.exit(1);
    }
    return;
  }
  for (const [url, text] of files) writeFileSync(url, text);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
